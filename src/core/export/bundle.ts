import { zipSync, strToU8 } from 'fflate';
import type { LaidOutPart } from '../build/layout';
import { writeBinarySTL } from './stl';
import { write3MF } from './threemf';
import type { RawMesh } from '../kernel/types';

/** How many distinct plates a set of parts was laid out across. */
function plateCount(parts: readonly LaidOutPart[]): number {
  return new Set(parts.map((p) => p.plate ?? 0)).size;
}

/** `plate-2/` when there is more than one plate, and nothing when there is not. */
function plateDir(part: LaidOutPart, plates: number): string {
  return plates > 1 ? `plate-${(part.plate ?? 0) + 1}/` : '';
}

function asMesh(part: LaidOutPart): RawMesh {
  return {
    position: part.positions,
    index: part.index,
    numProp: 3,
    bbox: { min: [0, 0, 0], max: part.size },
    stats: {
      volumeMm3: 0,
      areaMm2: 0,
      genus: 0,
      tris: part.index.length / 3,
    },
  };
}

/**
 * One STL per part, zipped with a readme.
 *
 * Parts are never merged into a single STL: a slicer would read several
 * touching bodies as one object with internal walls.
 */
export function writeStlBundle(
  parts: readonly LaidOutPart[],
  opts: { title: string; notes?: readonly string[] },
): Uint8Array {
  const files: Record<string, Uint8Array> = {};
  const plates = plateCount(parts);
  const lines = [
    opts.title,
    '='.repeat(opts.title.length),
    '',
    'Generated by 3D Print Generator. All dimensions are in millimetres.',
  ];
  if (plates > 1) {
    lines.push(
      '',
      `This model does not fit one bed. It is laid out across ${plates} plates, a`,
      'folder each; print them one after the other.',
    );
  }
  lines.push('', 'Parts:');

  const used = new Map<string, number>();
  let shownPlate = -1;
  for (const part of parts) {
    const base = part.name.replace(/[\/:*?"<>|]+/g, '-');
    const n = (used.get(base) ?? 0) + 1;
    used.set(base, n);
    const stem = n === 1 ? base : `${base}-${n}`;
    const filename = `${plateDir(part, plates)}${stem}.stl`;

    files[filename] = new Uint8Array(writeBinarySTL(asMesh(part), part.name));
    if (plates > 1 && (part.plate ?? 0) !== shownPlate) {
      shownPlate = part.plate ?? 0;
      lines.push(`  [plate ${shownPlate + 1}]`);
    }
    lines.push(
      `  ${stem.padEnd(28)} ${part.size.map((v) => v.toFixed(1)).join(' x ')} mm`,
    );
  }

  if (opts.notes?.length) {
    lines.push('', 'Printing notes:');
    for (const note of opts.notes) lines.push(`  - ${note}`);
  }

  files['README.txt'] = strToU8(lines.join('\r\n') + '\r\n');
  return zipSync(files, { level: 6 });
}

/**
 * One 3MF per plate, zipped.
 *
 * A 3MF is a plate, not a project: a slicer opening one expects what is inside
 * to sit on the bed. So a model that needs three beds is three files, each with
 * its own parts centred on the origin -- never one file with plate 2 shifted
 * 280 mm to the right, which every slicer flags as off-bed and which the user
 * then has to take apart by hand.
 */
export function write3mfBundle(
  parts: readonly LaidOutPart[],
  opts: { title: string; base: string; notes?: readonly string[]; thumbnail?: Uint8Array },
): Uint8Array {
  const plates = plateCount(parts);
  const files: Record<string, Uint8Array> = {};
  for (let i = 0; i < plates; i++) {
    const onPlate = parts.filter((p) => (p.plate ?? 0) === i);
    if (onPlate.length === 0) continue;
    files[`${opts.base}-plate-${i + 1}.3mf`] = write3MF(onPlate, {
      title: `${opts.title} - plate ${i + 1} of ${plates}`,
      // Only the first file carries the preview image: it is a picture of the
      // whole model, and on plate 3 it would be a picture of parts that are
      // not in that file.
      thumbnail: i === 0 ? opts.thumbnail : undefined,
    });
  }

  const lines = [
    opts.title,
    '='.repeat(opts.title.length),
    '',
    `This model does not fit one bed. It is ${plates} plates, one 3MF each;`,
    'print them one after the other.',
  ];
  if (opts.notes?.length) {
    lines.push('', 'Printing notes:');
    for (const note of opts.notes) lines.push(`  - ${note}`);
  }
  files['README.txt'] = strToU8(lines.join('\r\n') + '\r\n');
  return zipSync(files, { level: 6 });
}
