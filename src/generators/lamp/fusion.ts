import { strToU8, zipSync } from 'fflate';
import { shadeInner, shadeSurface, type Derived } from './geometry';
import { baseProfilePoints } from './parts/base';
import { flangeThickness } from './parts/shade';

const TAU = Math.PI * 2;

/** Folder, script and manifest must share this name or Fusion will not load it. */
export const FUSION_SCRIPT_NAME = 'TableLamp';

/**
 * How many cross-sections the shade is lofted through.
 *
 * Enough to hold the bulge (one every 5 mm) and the twist (no more than 6
 * degrees of turn between neighbours). The sections are sampled along the
 * flutes rather than at fixed angles -- see `shadeSections` -- so the loft is
 * joining a rib to the same rib, and it takes far fewer sections than the
 * preview mesh has rows.
 */
export function sectionCount(d: Derived): number {
  const twistDeg = Math.abs(d.twistRad) * (180 / Math.PI);
  return Math.min(60, Math.max(8, Math.ceil(Math.max(d.shadeH / 5, twistDeg / 6))));
}

/** Points round one section, per surface: the loft is only as good as these. */
function pointsPerSection(d: Derived): number {
  return Math.min(480, d.thetaSteps);
}

interface Section {
  readonly z: number;
  readonly outer: readonly (readonly [number, number])[];
  readonly inner: readonly (readonly [number, number])[];
}

/**
 * The shade as a stack of closed curves, hem first, in the shade's own frame.
 *
 * Sample j of every section sits at the same flute PHASE, theta + spin, not the
 * same angle. Fusion's loft joins sample j to sample j, so this is what makes
 * the lofted surface run up the ribs the way the twist does -- sampled at fixed
 * angles instead, the loft would cut straight up across them and smear sixty
 * helical ribs into a wobble.
 */
export function shadeSections(d: Derived): Section[] {
  const ns = sectionCount(d);
  const nt = pointsPerSection(d);
  const out: Section[] = [];
  for (let i = 0; i <= ns; i++) {
    const z = (i / ns) * d.shadeH;
    const spin = d.twistRad * (z / d.shadeH);
    const outer: [number, number][] = [];
    const inner: [number, number][] = [];
    for (let j = 0; j < nt; j++) {
      const th = (j / nt) * TAU - spin;
      const c = Math.cos(th);
      const s = Math.sin(th);
      const ro = shadeSurface(d, z, th);
      const ri = shadeInner(d, z, th);
      outer.push([ro * c, ro * s]);
      inner.push([ri * c, ri * s]);
    }
    out.push({ z, outer, inner });
  }
  return out;
}

/** The ring-mount fitter as an outline and a hole, or null in the base mount. */
function flangeOutline(d: Derived): { z: number; t: number; rIn: number; outline: [number, number][] } | null {
  if (d.mount !== 'ring') return null;
  const nt = pointsPerSection(d);
  const z = d.seatH;
  const pitch = d.spokes > 0 ? TAU / d.spokes : 0;
  const outline: [number, number][] = [];
  for (let j = 0; j < nt; j++) {
    const th = (j / nt) * TAU;
    let r: number;
    const a = pitch > 0 ? ((th % pitch) + pitch) % pitch : 0;
    if (pitch > 0 && Math.min(a, pitch - a) > d.spokeHalf) {
      r = d.hubR;
    } else {
      // Three quarters of the way out through the wall, as in the mesh.
      const ro = shadeSurface(d, z, th);
      r = ro - 0.25 * (ro - shadeInner(d, z, th));
    }
    outline.push([r * Math.cos(th), r * Math.sin(th)]);
  }
  return { z, t: flangeThickness(d), rIn: d.socket.thread / 2 + d.fit, outline };
}

const f = (v: number): string => (Math.abs(v) < 5e-4 ? '0' : v.toFixed(3).replace(/\.?0+$/, ''));
const pairs = (pts: readonly (readonly [number, number])[]): string =>
  `[${pts.map(([a, b]) => `(${f(a)},${f(b)})`).join(',')}]`;

/**
 * A Fusion 360 script that rebuilds this lamp as native, editable solids.
 *
 * Not a mesh import. A mesh arrives in Fusion as a few hundred thousand
 * triangles that no Fusion tool will fillet, shell or press-pull; this arrives
 * as a timeline -- a revolved base, a lofted shade and a cut for the cord --
 * with every sketch still there to edit. The geometry is sampled from exactly
 * the functions the preview is built from, so it is the same lamp.
 *
 * Everything is written in millimetres and scaled on the way in: Fusion's API
 * works in centimetres whatever the document's units say.
 */
export function fusionScript(d: Derived, title: string): string {
  const sections = shadeSections(d);
  const flange = flangeOutline(d);
  const notchW = d.socket.cord + 1.6;
  const notchH = d.socket.cord + 2.6;

  const lines: string[] = [];
  lines.push(
    `"""${title} - generated by 3D Print Generator.`,
    '',
    'Run from Fusion 360: Utilities > Add-Ins > Scripts and Add-Ins, "+" >',
    '"Script or add-in from device", pick this folder, then Run. It opens a new',
    'design and builds the lamp as solid bodies, one component per part, placed',
    'where they sit in the assembled lamp. Lofting the shade takes a minute.',
    '',
    'All numbers below are millimetres.',
    '"""',
    'import adsk.core, adsk.fusion, traceback',
    '',
    'MM = 0.1  # the Fusion API works in centimetres',
    '',
    `SHADE_Z = ${f(d.shadeZ)}  # hem height in the assembled lamp`,
  );
  lines.push('# One section per entry: (height above the hem, outer loop, inner loop).');
  lines.push('SHADE_SECTIONS = [');
  for (const s of sections) {
    lines.push(`  (${f(s.z)}, ${pairs(s.outer)}, ${pairs(s.inner)}),`);
  }
  lines.push(']');
  lines.push('');
  lines.push('# Base section to revolve about Z, as (radius, height).');
  lines.push(`BASE_PROFILE = ${pairs(baseProfilePoints(d))}`);
  lines.push(`CORD_NOTCH = (${f(notchW)}, ${f(notchH)}, ${f(d.rBase * 2 + 20)})  # width, height, reach toward +Y`);
  if (flange) {
    lines.push(
      `FLANGE = (${f(flange.z)}, ${f(flange.t)}, ${f(flange.rIn)}, ${pairs(flange.outline)})  # height above hem, thickness, hole radius, outline`,
    );
  } else {
    lines.push('FLANGE = None  # the shade sits on the base; there is no fitter');
  }
  lines.push(PY_BODY);
  return lines.join('\n') + '\n';
}

const PY_BODY = `

def P(x, y, z):
    return adsk.core.Point3D.create(x * MM, y * MM, z * MM)


def new_component(root, name):
    occ = root.occurrences.addNewComponent(adsk.core.Matrix3D.create())
    comp = occ.component
    comp.name = name
    return comp


def plane_at(comp, z):
    if abs(z) < 1e-9:
        return comp.xYConstructionPlane
    pi = comp.constructionPlanes.createInput()
    pi.setByOffset(comp.xYConstructionPlane, adsk.core.ValueInput.createByReal(z * MM))
    return comp.constructionPlanes.add(pi)


def closed_spline(sk, pts, z):
    coll = adsk.core.ObjectCollection.create()
    for x, y in pts:
        coll.add(sk.modelToSketchSpace(P(x, y, z)))
    spline = sk.sketchCurves.sketchFittedSplines.add(coll)
    spline.isClosed = True
    return spline


def closed_polyline(sk, pts):
    lines = sk.sketchCurves.sketchLines
    first = prev = None
    for p in pts:
        if prev is None:
            prev = first = sk.sketchPoints.add(p)
            continue
        ln = lines.addByTwoPoints(prev, p)
        prev = ln.endSketchPoint
    lines.addByTwoPoints(prev, first)


def loft(comp, profiles, name):
    li = comp.features.loftFeatures.createInput(adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    for prof in profiles:
        li.loftSections.add(prof)
    li.isSolid = True
    body = comp.features.loftFeatures.add(li).bodies.item(0)
    body.name = name
    return body


def build_shade(comp):
    outer, inner = [], []
    for i, (z, out_pts, in_pts) in enumerate(SHADE_SECTIONS):
        zz = SHADE_Z + z
        plane = plane_at(comp, zz)
        so = comp.sketches.add(plane)
        so.name = 'Shade outer %02d' % i
        so.isComputeDeferred = True
        closed_spline(so, out_pts, zz)
        so.isComputeDeferred = False
        outer.append(so.profiles.item(0))
        si = comp.sketches.add(plane)
        si.name = 'Shade inner %02d' % i
        si.isComputeDeferred = True
        closed_spline(si, in_pts, zz)
        si.isComputeDeferred = False
        inner.append(si.profiles.item(0))

    shell = loft(comp, outer, 'Shade')
    core = loft(comp, inner, 'Shade core')
    tools = adsk.core.ObjectCollection.create()
    tools.add(core)
    ci = comp.features.combineFeatures.createInput(shell, tools)
    ci.operation = adsk.fusion.FeatureOperations.CutFeatureOperation
    ci.isKeepToolBodies = False
    comp.features.combineFeatures.add(ci)

    if FLANGE:
        z, t, r_in, outline = FLANGE
        zz = SHADE_Z + z
        sk = comp.sketches.add(plane_at(comp, zz))
        sk.name = 'Fitter'
        sk.isComputeDeferred = True
        closed_polyline(sk, [sk.modelToSketchSpace(P(x, y, zz)) for x, y in outline])
        sk.sketchCurves.sketchCircles.addByCenterRadius(sk.modelToSketchSpace(P(0, 0, zz)), r_in * MM)
        sk.isComputeDeferred = False
        prof = max((sk.profiles.item(k) for k in range(sk.profiles.count)),
                   key=lambda p: p.profileLoops.count)
        ei = comp.features.extrudeFeatures.createInput(prof, adsk.fusion.FeatureOperations.JoinFeatureOperation)
        ei.setDistanceExtent(False, adsk.core.ValueInput.createByReal(t * MM))
        ei.participantBodies = [shell]
        comp.features.extrudeFeatures.add(ei)
    return shell


def build_base(comp):
    sk = comp.sketches.add(comp.xZConstructionPlane)
    sk.name = 'Base profile'
    closed_polyline(sk, [sk.modelToSketchSpace(P(r, 0, z)) for r, z in BASE_PROFILE])
    ri = comp.features.revolveFeatures.createInput(
        sk.profiles.item(0), comp.zConstructionAxis,
        adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    ri.setAngleExtent(False, adsk.core.ValueInput.createByString('360 deg'))
    body = comp.features.revolveFeatures.add(ri).bodies.item(0)
    body.name = 'Base'

    # The cord's way out: an arch through the back of the foot, toward +Y.
    w, h, reach = CORD_NOTCH
    straight = max(0.2, h - w / 2)
    ns = comp.sketches.add(comp.xZConstructionPlane)
    ns.name = 'Cord notch'
    q = lambda x, z: ns.modelToSketchSpace(P(x, 0, z))
    lines = ns.sketchCurves.sketchLines
    a = lines.addByTwoPoints(q(w / 2, straight), q(w / 2, -1))
    b = lines.addByTwoPoints(a.endSketchPoint, q(-w / 2, -1))
    c = lines.addByTwoPoints(b.endSketchPoint, q(-w / 2, straight))
    ns.sketchCurves.sketchArcs.addByThreePoints(c.endSketchPoint, q(0, straight + w / 2), a.startSketchPoint)
    normal = comp.xZConstructionPlane.geometry.normal
    direction = (adsk.fusion.ExtentDirections.PositiveExtentDirection if normal.y > 0
                 else adsk.fusion.ExtentDirections.NegativeExtentDirection)
    ei = comp.features.extrudeFeatures.createInput(ns.profiles.item(0), adsk.fusion.FeatureOperations.CutFeatureOperation)
    ei.setOneSideExtent(adsk.fusion.DistanceExtentDefinition.create(adsk.core.ValueInput.createByReal(reach * MM)), direction)
    ei.participantBodies = [body]
    comp.features.extrudeFeatures.add(ei)
    return body


def run(context):
    ui = None
    try:
        app = adsk.core.Application.get()
        ui = app.userInterface
        app.documents.add(adsk.core.DocumentTypes.FusionDesignDocumentType)
        design = adsk.fusion.Design.cast(app.activeProduct)
        design.designType = adsk.fusion.DesignTypes.ParametricDesignType
        root = design.rootComponent
        build_base(new_component(root, 'Base'))
        build_shade(new_component(root, 'Shade'))
        app.activeViewport.fit()
    except:
        if ui:
            ui.messageBox('Building the lamp failed:\\n{}'.format(traceback.format_exc()))
`;

/**
 * The script as Fusion wants to be handed it: a folder holding the script and
 * a manifest of the same name, zipped with a readme.
 */
export function fusionBundle(d: Derived, title: string): Uint8Array {
  const n = FUSION_SCRIPT_NAME;
  const manifest = {
    autodeskProduct: 'Fusion',
    type: 'script',
    author: '3D Print Generator',
    description: { '': `${title} as editable solids` },
    supportedOS: 'windows|mac',
    editEnabled: true,
  };
  const readme = [
    `${title} - Fusion 360`,
    '',
    `The ${n} folder is a Fusion 360 script that builds this lamp as editable`,
    'solid bodies - a revolved base and a lofted shade, with every sketch in the',
    'timeline - rather than a mesh you cannot fillet or shell.',
    '',
    '1. Unzip this somewhere you will keep it.',
    '2. In Fusion 360: Utilities > Add-Ins > Scripts and Add-Ins (Shift+S).',
    `3. Click "+" > "Script or add-in from device" and choose the ${n} folder.`,
    `4. Select ${n} in the list and click Run.`,
    '',
    'It opens a new design. The shade takes a minute to loft; leave it alone',
    'until the viewport zooms to fit. All dimensions are in millimetres.',
    '',
  ].join('\r\n');
  return zipSync(
    {
      [`${n}/${n}.py`]: strToU8(fusionScript(d, title)),
      [`${n}/${n}.manifest`]: strToU8(JSON.stringify(manifest, null, 2)),
      'README.txt': strToU8(readme),
    },
    { level: 6 },
  );
}
